import { readFileSync, existsSync, readdirSync, statSync } from "node:fs";
const read = (p) => readFileSync(p, "utf8");
const checks = [];
function check(name, ok, detail="") {
  checks.push({name,ok,detail});
  console.log((ok ? "PASS " : "FAIL ") + name + (detail ? " · " + detail : ""));
  if (!ok) process.exitCode = 1;
}
const plugin=read("android/app/src/main/java/com/mvmcmd/launcher/MvmLauncherPlugin.java");
const main=read("android/app/src/main/java/com/mvmcmd/launcher/MainActivity.java");
const qr=read("android/app/src/main/java/com/mvmcmd/launcher/MvmQrActivity.java");
const tile=read("android/app/src/main/java/com/mvmcmd/launcher/MvmQrTileService.java");
const wp=read("android/app/src/main/java/com/mvmcmd/launcher/MvmWallpaperActivity.java");
const wpSvc=read("android/app/src/main/java/com/mvmcmd/launcher/MvmHomeWallpaperService.java");
const manifest=read("android/app/src/main/AndroidManifest.xml");
const strings=read("android/app/src/main/res/values/strings.xml");
check("Capacitor plugin annotation", /@CapacitorPlugin\(name = "MvmLauncher"\)/.test(plugin));
check("MvmLauncher registration", /registerPlugin\(MvmLauncherPlugin.class\)/.test(main));
check("camera bridge", /openCamera/.test(plugin));
check("QR bridge", /openQr/.test(plugin));
check("wallpaper bridge", /openWallpaper/.test(plugin));
check("temperature bridge", /openTemperature/.test(plugin));
check("QR formats", /FORMAT_ALL_FORMATS/.test(qr));
check("QR image picker", /ActivityResultContracts.GetContent/.test(qr));
check("QR file input", /InputImage.fromFilePath/.test(qr));
check("QR tile launch", /startActivityAndCollapse/.test(tile));
check("QR tile service manifest", /android.service.quicksettings.action.QS_TILE/.test(manifest));
check("QR tile binding", /BIND_QUICK_SETTINGS_TILE/.test(manifest));
check("live wallpaper permission", /SET_WALLPAPER/.test(manifest));
check("wallpaper service declaration", /android.service.wallpaper.WallpaperService/.test(manifest));
check("wallpaper service implementation", /WallpaperService/.test(wpSvc));
check("wallpaper apply action", /ACTION_CHANGE_LIVE_WALLPAPER/.test(wp));
check("wallpaper component extra", /EXTRA_LIVE_WALLPAPER_COMPONENT/.test(wp));
check("wallpaper description", /wallpaper_description/.test(strings));
const packDir="scripts/wallpapers-pack-b64";
const parts=existsSync(packDir)?readdirSync(packDir).filter(name=>/^part-/.test(name) && statSync(`${packDir}/${name}`).isFile()):[];
check("wallpaper pack", existsSync(packDir) && parts.length===11, `parts=${parts.length}`);
check("launcher logo", existsSync("android/app/src/main/res/drawable/mvmcmd_logo.xml"));
if (process.exitCode) throw new Error("Native launcher verification failed.");
console.log("MVMCMD native launcher verification: PASS");